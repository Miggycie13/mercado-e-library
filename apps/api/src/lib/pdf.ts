import { PDFDocument, StandardFonts, rgb } from "pdf-lib";

function pdfSafe(value: string) {
  return value.replace(/[^\x20-\x7E]/g, " ").replace(/\s+/g, " ").trim();
}

function wrap(text: string, width = 86) {
  const words = pdfSafe(text).split(" ");
  const lines: string[] = [];
  let line = "";
  for (const word of words) {
    const next = line ? `${line} ${word}` : word;
    if (next.length > width) {
      if (line) lines.push(line);
      line = word;
    } else {
      line = next;
    }
  }
  if (line) lines.push(line);
  return lines;
}

export async function bibliographicPdf(book: {
  title: string;
  author: string;
  year: number;
  category: string;
  description: string;
  sourceUrl?: string | null;
}) {
  const doc = await PDFDocument.create();
  const page = doc.addPage([612, 792]);
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  page.drawRectangle({ x: 0, y: 742, width: 612, height: 50, color: rgb(0.12, 0.22, 0.18) });
  page.drawText("MERCADO E-LIBRARY", { x: 48, y: 762, size: 12, font: bold, color: rgb(0.96, 0.93, 0.86) });
  const lines = [
    ...wrap(book.title, 42).map((line) => ({ text: line, size: 18, font: bold })),
    { text: pdfSafe(`${book.author}  ·  ${book.year}  ·  ${book.category}`), size: 11, font },
    { text: " ", size: 10, font },
    ...wrap(book.description).map((line) => ({ text: line, size: 11, font })),
    { text: " ", size: 10, font },
    ...wrap(
      book.sourceUrl
        ? `Public-domain catalog link: ${book.sourceUrl}`
        : "No external source link is stored for this record."
    ).map((line) => ({ text: line, size: 10, font })),
    { text: " ", size: 10, font },
    ...wrap(
      "This PDF is an original bibliographic card generated by the library. It is not a copy of the underlying book."
    ).map((line) => ({ text: line, size: 10, font })),
  ];
  let y = 700;
  for (const line of lines) {
    if (y < 64) break;
    page.drawText(line.text || " ", { x: 48, y, size: line.size, font: line.font, color: rgb(0.12, 0.1, 0.08) });
    y -= line.size + 8;
  }
  doc.setTitle(pdfSafe(book.title));
  doc.setAuthor(pdfSafe(book.author));
  return Buffer.from(await doc.save());
}
